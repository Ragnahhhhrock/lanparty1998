// An <svg> string for an icon. `size` is the CSS pixel size (16 or 32).
export function icon(name, size = 16) {
  const rows = ICONS[name] ?? ICONS.programs;
  let rects = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length;) {
      const c = row[x];
      let run = 1;
      while (row[x + run] === c) run++;
      if (c !== '.') rects += `<rect x="${x}" y="${y}" width="${run}" height="1" style="fill:var(${PALETTE[c]})"/>`;
      x += run;
    }
  });
  return `<svg class="px-icon" width="${size}" height="${size}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true" focusable="false">${rects}</svg>`;
}
